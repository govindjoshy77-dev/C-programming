#include<stdio.h>
#include<conio.h>
void main()
{
	int i=65;
	float f=6.2;
	double d=28.689;
	char c='O';
	
	printf("*********Type Conversion***********\n");
	printf("Integer to float = %f\n",(float)i);
	printf("float to Integer = %d\n",(int)f);
	printf("Float to Double = %lf\n",(double)f);
	printf("Double to float = %f\n",(float)d);
	printf("Char to Integer = %d\n",(int)c);
	printf("Integer to Char= %c\n",(char)i);


}
